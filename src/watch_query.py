def _expand_subject_countries(codes: Sequence[str]) -> list[str]:
    """Broad → children expansion mirroring webapp `expandBroadToChildren`.

    A pick of "EUR" matches every European country code AND keeps "EUR"
    itself (because some articles get tagged at the regional level). A
    pick of "FR" matches only "FR" — leaf codes do NOT pull in the
    region.
    """
    out: set[str] = set()
    for raw in codes:
        if not raw:
            continue
        code = str(raw).upper()
        out.add(code)
        children = REGION_MEMBERS.get(code)
        if children:
            out.update(children)
    return sorted(out)
